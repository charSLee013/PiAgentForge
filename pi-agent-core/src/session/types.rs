/// Resolved conversation context produced by `build_session_context`.
///
/// This is the data that gets sent to the LLM: a flat list of messages with
/// the current thinking level and model.
#[derive(Debug, Clone)]
pub struct SessionContext {
    /// Messages in conversation order.
    pub messages: Vec<Message>,
    /// Current thinking level (defaults to `"off"`).
    pub thinking_level: String,
    /// Current model (provider + model ID).
    pub model: Option<(String, String)>,
}

impl Default for SessionContext {
    fn default() -> Self {
        Self { messages: Vec::new(), thinking_level: "off".to_string(), model: None }
    }
}

