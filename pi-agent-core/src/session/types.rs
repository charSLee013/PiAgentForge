//! Session data types for JSONL persistence.
//!
//! Mirrors the TS types from:
//! - packages/agent/src/harness/session/jsonl-storage.ts
//! - packages/coding-agent/src/core/session-manager.ts
//!
//! A session is stored as an append-only JSONL file where the first line is a
//! `SessionHeader` and subsequent lines are `SessionEntry` values. Entries form
//! a tree via `id`/`parent_id` pointers. The "leaf" tracks the current position;
//! appending creates a child of the current leaf; branching moves the leaf to a
//! different node.

use serde::{Deserialize, Serialize};
use std::collections::HashMap;

// Re-export pi-ai-core Message for session context.
pub use pi_ai_core::types::Message;

/// Unique session entry identifier.
pub type EntryId = String;

/// Error type for session operations.
#[derive(Debug, thiserror::Error)]
pub enum SessionError {
    /// I/O error (file read/write).
    #[error("IO error: {0}")]
    Io(#[from] std::io::Error),

    /// JSON serialization / deserialization error.
    #[error("JSON error: {0}")]
    Json(#[from] serde_json::Error),

    /// The session file is malformed or missing a header.
    #[error("Invalid session file: {0}")]
    InvalidSession(String),

    /// Referenced entry does not exist.
    #[error("Entry {0} not found")]
    EntryNotFound(EntryId),
}

// ---------------------------------------------------------------------------
// Session header
// ---------------------------------------------------------------------------

/// Session header — the first line in a JSONL session file.
///
/// Mirrors `SessionHeader` in the TS `session-manager.ts`.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SessionHeader {
    /// Always `"session"`.
    pub r#type: String,
    /// Session format version; `None` for v1 sessions.
    #[serde(default)]
    pub version: Option<u32>,
    /// Unique session identifier.
    pub id: EntryId,
    /// ISO 8601 timestamp.
    pub timestamp: String,
    /// Working directory when the session was started.
    pub cwd: String,
    /// Path to parent session file (if this session was forked).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub parent_session: Option<String>,
}

impl SessionHeader {
    /// Create a new v3 session header.
    pub fn new(cwd: impl Into<String>, id: EntryId) -> Self {
        Self {
            r#type: "session".to_string(),
            version: Some(3),
            id,
            timestamp: chrono::Utc::now().to_rfc3339(),
            cwd: cwd.into(),
            parent_session: None,
        }
    }

    /// Create a new v3 session header referencing a parent session.
    pub fn with_parent(cwd: impl Into<String>, id: EntryId, parent_session: impl Into<String>) -> Self {
        Self { parent_session: Some(parent_session.into()), ..Self::new(cwd, id) }
    }
}

