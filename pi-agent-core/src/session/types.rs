/// A single entry in the session tree.
///
/// Each line (after the header) in a JSONL session file is one of these.
/// The `type` field in the JSON discriminates the variant.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum SessionEntry {
    /// A user, assistant, or tool message.
    #[serde(rename = "message")]
    Message(MessageEntryData),
    /// A compaction summary.
    #[serde(rename = "compaction")]
    Compaction(CompactionEntryData),
    /// A thinking level change.
    #[serde(rename = "thinking_level_change")]
    ThinkingLevelChange(ThinkingLevelChangeEntryData),
    /// A model change.
    #[serde(rename = "model_change")]
    ModelChange(ModelChangeEntryData),
    /// A branch summary (context from an abandoned path).
    #[serde(rename = "branch_summary")]
    BranchSummary(BranchSummaryEntryData),
    /// A label / bookmark.
    #[serde(rename = "label")]
    Label(LabelEntryData),
    /// Extension-specific custom data (not sent to LLM).
    #[serde(rename = "custom")]
    Custom(CustomEntryData),
    /// Extension-injected message (sent to LLM).
    #[serde(rename = "custom_message")]
    CustomMessage(CustomMessageEntryData),
    /// Session metadata (display name, etc.).
    #[serde(rename = "session_info")]
    SessionInfo(SessionInfoEntryData),
}

impl SessionEntry {
    /// Returns the entry's unique identifier.
    pub fn id(&self) -> &str {
        match self {
            Self::Message(e) => &e.id,
            Self::Compaction(e) => &e.id,
            Self::ThinkingLevelChange(e) => &e.id,
            Self::ModelChange(e) => &e.id,
            Self::BranchSummary(e) => &e.id,
            Self::Label(e) => &e.id,
            Self::Custom(e) => &e.id,
            Self::CustomMessage(e) => &e.id,
            Self::SessionInfo(e) => &e.id,
        }
    }

    /// Returns the parent entry ID, if any.
    pub fn parent_id(&self) -> Option<&str> {
        match self {
            Self::Message(e) => e.parent_id.as_deref(),
            Self::Compaction(e) => e.parent_id.as_deref(),
            Self::ThinkingLevelChange(e) => e.parent_id.as_deref(),
            Self::ModelChange(e) => e.parent_id.as_deref(),
            Self::BranchSummary(e) => e.parent_id.as_deref(),
            Self::Label(e) => e.parent_id.as_deref(),
            Self::Custom(e) => e.parent_id.as_deref(),
            Self::CustomMessage(e) => e.parent_id.as_deref(),
            Self::SessionInfo(e) => e.parent_id.as_deref(),
        }
    }

    /// Returns the ISO 8601 timestamp string.
    pub fn timestamp(&self) -> &str {
        match self {
            Self::Message(e) => &e.timestamp,
            Self::Compaction(e) => &e.timestamp,
            Self::ThinkingLevelChange(e) => &e.timestamp,
            Self::ModelChange(e) => &e.timestamp,
            Self::BranchSummary(e) => &e.timestamp,
            Self::Label(e) => &e.timestamp,
            Self::Custom(e) => &e.timestamp,
            Self::CustomMessage(e) => &e.timestamp,
            Self::SessionInfo(e) => &e.timestamp,
        }
    }
}

/// A raw file entry — either a header or a session entry.
///
/// Used when parsing the raw lines of a JSONL file where we don't yet know
/// whether a line is the header or a body entry.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(untagged)]
pub enum FileEntry {
    /// Session header (first line).
    Header(SessionHeader),
    /// Session body entry (subsequent lines).
    Entry(SessionEntry),
}

