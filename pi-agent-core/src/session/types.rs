// Label cache
// ---------------------------------------------------------------------------

/// In-memory cache of resolved labels, keyed by target entry ID.
pub type LabelCache = HashMap<EntryId, String>;

/// Build a label cache from a slice of entries.
pub fn build_label_cache(entries: &[SessionEntry]) -> LabelCache {
    let mut cache = LabelCache::new();
    for entry in entries {
        if let SessionEntry::Label(label) = entry {
            if let Some(ref l) = label.label {
                let trimmed = l.trim();
                if !trimmed.is_empty() {
                    cache.insert(label.target_id.clone(), trimmed.to_string());
                } else {
                    cache.remove(&label.target_id);
                }
            } else {
                cache.remove(&label.target_id);
            }
        }
    }
    cache
}

