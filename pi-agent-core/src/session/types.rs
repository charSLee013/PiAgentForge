/// Generate a short entry ID (8 hex characters) with collision checking.
///
/// Mirrors `generateId()` / `generateEntryId()` in the TS source.
pub fn generate_entry_id(existing: &std::collections::HashSet<String>) -> EntryId {
    for _ in 0..100 {
        let id = uuid::Uuid::new_v4().simple().to_string()[..8].to_string();
        if !existing.contains(&id) {
            return id;
        }
    }
    // Fallback to full UUID on extreme collision.
    uuid::Uuid::new_v4().to_string()
}

/// Generate a session ID (full UUID).
///
/// Mirrors `createSessionId()` in the TS source.
pub fn create_session_id() -> EntryId {
    uuid::Uuid::new_v4().to_string()
}

/// Create an ISO 8601 timestamp string for the current moment.
pub fn now_timestamp() -> String {
    chrono::Utc::now().to_rfc3339()
}
